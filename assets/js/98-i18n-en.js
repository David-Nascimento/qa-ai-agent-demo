  var MESES = { jan: 'Jan', fev: 'Feb', mar: 'Mar', abr: 'Apr', mai: 'May', jun: 'Jun', jul: 'Jul', ago: 'Aug', set: 'Sep', out: 'Oct', nov: 'Nov', dez: 'Dec' };
  var L = '(?<![\\p{L}\\d])', R = '(?![\\p{L}\\d])';
  function esc(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }

  // frases longas primeiro; a primeira tradução de cada frase vale
  var visto = {};
  var regras = P.filter(function (p) { if (visto[p[0]]) return false; visto[p[0]] = 1; return true; })
    .sort(function (a, b) { return b[0].length - a[0].length; })
    .map(function (p) {
      var ini = /^[\p{L}\d]/u.test(p[0]) ? L : '';
      var fim = /[\p{L}\d]$/u.test(p[0]) ? R : '';
      return [new RegExp(ini + esc(p[0]) + fim, 'gu'), p[1].replace(/\$/g, '$$$$')];
    });

  var cache = new Map();
  function traduzir(texto) {
    if (!/[A-Za-zÀ-ú]/.test(texto) && !/\d,\d/.test(texto)) return texto;
    if (cache.has(texto)) return cache.get(texto);
    var t = texto;
    for (var i = 0; i < regras.length; i++) t = t.replace(regras[i][0], regras[i][1]);
    // datas "12 jan" -> "Jan 12"
    t = t.replace(/(\d{1,2}) (jan|fev|mar|abr|mai|jun|jul|ago|set|out|nov|dez)(?![a-zà-ú])/g, function (m, d, mes) { return MESES[mes] + ' ' + d; });
    t = t.replace(/\((\d+) de (\d+)\)/g, '($1 of $2)');
    // decimais "95,5%" -> "95.5%"
    t = t.replace(/(\d),(\d)/g, '$1.$2');
    // plural correto: "1 runs" -> "1 run"
    t = t.replace(/\b1 (runs|scenarios|failures|pipelines|components|projects|people)\b/g, function (m, w) { return '1 ' + (w === 'people' ? 'person' : w.slice(0, -1)); });
    cache.set(texto, t);
    return t;
  }

  var ATTRS = ['placeholder', 'title', 'aria-label', 'alt'];
  function noTexto(n) {
    var v = n.nodeValue;
    if (!v || !v.trim()) return;
    var p = n.parentElement;
    if (!p || p.closest('script,style,[data-no-i18n],textarea')) return;
    var m = v.match(/^(\s*)([\s\S]*?)(\s*)$/);
    var novo = m[1] + traduzir(m[2]) + m[3];
    if (novo !== v) n.nodeValue = novo;
  }
  function varrer(raiz) {
    if (raiz.nodeType === 3) return noTexto(raiz);
    if (raiz.nodeType !== 1 || raiz.closest('[data-no-i18n]')) return;
    var w = document.createTreeWalker(raiz, NodeFilter.SHOW_TEXT);
    var n;
    while ((n = w.nextNode())) noTexto(n);
    var els = raiz.querySelectorAll('[placeholder],[title],[aria-label],[alt]');
    for (var i = 0; i < els.length; i++) {
      for (var j = 0; j < ATTRS.length; j++) {
        var v = els[i].getAttribute(ATTRS[j]);
        if (v) { var t = traduzir(v); if (t !== v) els[i].setAttribute(ATTRS[j], t); }
      }
    }
  }

  function iniciar() {
    document.title = 'QA AI Agent – Demo';
    varrer(document.body);
    new MutationObserver(function (muts) {
      muts.forEach(function (m) {
        if (m.type === 'characterData') noTexto(m.target);
        else m.addedNodes.forEach(varrer);
        if (m.type === 'attributes') {
          var v = m.target.getAttribute(m.attributeName);
          var t = v && traduzir(v);
          if (t && t !== v) m.target.setAttribute(m.attributeName, t);
        }
      });
    }).observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ATTRS });
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', iniciar); else iniciar();
